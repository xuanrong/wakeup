import 'holiday_table.dart';

/// 内嵌离线节假日表（当年 + 次年）。
/// 数据源：国务院办公厅年度放假安排通知。表过期时由 HolidayService 降级为默认周几。
class BuiltInHolidays {
  BuiltInHolidays._();

  /// 年份 → 节假日表。每年 11 月左右发布次年安排，跨年时补录。
  static const Map<int, HolidayTable> tables = {
    2026: HolidayTable(
      year: 2026,
      holidays: {
        // 元旦 1/1-1/3
        '2026-01-01', '2026-01-02', '2026-01-03',
        // 春节 2/15-2/23
        '2026-02-15', '2026-02-16', '2026-02-17', '2026-02-18', '2026-02-19',
        '2026-02-20', '2026-02-21', '2026-02-22', '2026-02-23',
        // 清明 4/4-4/6
        '2026-04-04', '2026-04-05', '2026-04-06',
        // 劳动节 5/1-5/5
        '2026-05-01', '2026-05-02', '2026-05-03', '2026-05-04', '2026-05-05',
        // 端午 6/19-6/21
        '2026-06-19', '2026-06-20', '2026-06-21',
        // 中秋 9/25-9/27
        '2026-09-25', '2026-09-26', '2026-09-27',
        // 国庆 10/1-10/7
        '2026-10-01', '2026-10-02', '2026-10-03', '2026-10-04', '2026-10-05',
        '2026-10-06', '2026-10-07',
      },
      makeupWorkdays: {
        '2026-01-04', // 周日补元旦
        '2026-02-14', '2026-02-28', // 周六补春节
        '2026-05-09', // 周六补劳动节
        '2026-09-20', '2026-10-10', // 周日/周六补国庆
      },
    ),
    2027: HolidayTable(year: 2027),
  };

  /// 取某年表格；无则返回空表（降级为默认周几）。
  static HolidayTable tableFor(int year) =>
      tables[year] ?? HolidayTable(year: year);
}
